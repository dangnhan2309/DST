# Different Ways to Structure a Topic Name

# 1. Simple Noun Phrases (NP)
#    - Single Noun: "Mathematics", "Science", "Evolution"
#    - Compound Noun: "Machine Learning", "Climate Change"

# 2. Noun Phrases with Modifiers
#    - Adjective + Noun: "Artificial Intelligence", "Quantum Computing"
#    - Participle + Noun: "Receding Glaciers", "Changing Climate"
#    - Noun + Noun: "Data Science", "Speech Recognition"

# 3. Prepositional Phrases
#    - Noun + Preposition + Noun: "Impact of Social Media", "Future of Work"

# 4. Gerund Phrases (Verb-ing Phrases)
#    - Gerund + Object: "Managing Big Data", "Understanding Neural Networks"

# 5. Infinitive Phrases
#    - To + Verb + Object: "How to Build a Website", "Ways to Improve Data Security"

# 6. Relative Clauses
#    - Noun + Relative Clause: "The Effects That Climate Change Has on Wildlife"

# 7. Questions as Topic Names
#    - Wh- Questions: "What Is Artificial Intelligence?", "Why Do We Dream?"
